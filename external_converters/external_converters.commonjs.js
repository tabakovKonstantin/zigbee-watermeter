function uint48ToNumber(value) {
    if (typeof value === 'number') {
        return value;
    }

    if (typeof value === 'bigint') {
        return Number(value);
    }

    if (value && typeof value === 'object') {
        const low = value.low ?? value[0] ?? 0;
        const high = value.high ?? value[1] ?? 0;
        return (high * 0x100000000) + low;
    }

    return value;
}

